"""Resumable full-wave azimuth-sweep engine (GUI- and CLI-drivable).

STATE = THE FILESYSTEM, so every failure mode resumes cleanly:
  out/sweeps/<name>/config.json   the sweep definition (written once)
  out/sweeps/<name>/az{ddd}.npz   one file per COMPLETED azimuth,
                                  written atomically (tmp + os.replace -
                                  a killed process can never leave a
                                  half-written azimuth)
  out/sweeps/<name>/status.json   heartbeat + progress for the GUI
  out/sweeps/<name>/run.log       runner stdout
  out/sweeps/<name>/STOP          cooperative stop flag: the GUI Stop
                                  button creates it; checked between
                                  azimuths AND mid-trace via the solver
                                  progress callback (the in-flight
                                  azimuth is discarded and redone on
                                  continue; all saved files are final)
Continue = start again with the same config: completed azimuths are
detected by their files and skipped. Different specimens/configs are
just different sweep directories.

Protocol per azimuth = the VALIDATED rotated-specimen mechanism
(rotation_test.rotated_grid, same as all existing fw_az results):
specimen grains AND c-axes rotate against the fixed probe; labels
solver, order 8, fluid damp 0.02, record to record_factor*D/c.
"""
